const tileDeclaration = (p: TearPreset) => `  --${p.name}: ${tornPolygon(p)};`
const sheetClass = (p: TearPreset) =>
  `  .kcc-${p.name} {\n    --r: ${p.tilt ?? 0};\n    --blank-dir: ${p.blank?.dir ?? 1};\n  }`
const tileClass = (p: TearPreset) => `  .kcc-${p.name} {\n    --tear: var(--${p.name});\n  }`

// A slip holds its own sheet, fall and blank as direct children, so child combinators keep a nested slip's
// preset from reaching an outer sheet. A blank takes the polygon of the preset its slip names as its blank.
const clipRule = (p: TearPreset) => {
  const selectors = [
    `.kcc-${p.name} > .kcc-torn > .kcc-sheet`,
    `.kcc-${p.name} > .kcc-fall > span`,
    ...SHEET_TEARS.filter((q) => q.blank?.tear === p.name).map((q) => `.kcc-${q.name} > .kcc-blank > span`),
  ]
  return `  ${selectors.join(',\n  ')} {\n    clip-path: ${tornPolygon(p)};\n  }`
}

export function tearsCss(): string {
  return [
    '/* GENERATED by `yarn tears` from Features/Torn/tears.ts. Do not edit: tears.test.ts diffs this file against the generator. */',
    ':root {',
    ...TILE_TEARS.map(tileDeclaration),
    '}',
    '',
    '@layer components {',
    ...SHEET_TEARS.map(sheetClass),
    ...SHEET_TEARS.map(clipRule),
    ...TILE_TEARS.map(tileClass),
    '}',
    '',
  ].join('\n')
}
